"""Student PowerPoint generation tool.

Creates a real .pptx locally. Slide content is generated by the configured
LLM when available; the file writer itself is deterministic and does not
execute arbitrary code.
"""
from __future__ import annotations
import json, re
from pathlib import Path
from datetime import datetime
from pptx import Presentation
from pptx.util import Inches, Pt

def _safe_name(title: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "_", title.strip()).strip("_")
    return name[:80] or "presentation"

def _fallback_outline(title: str, n: int) -> list[dict]:
    slides=[{"title": title, "bullets":[f"Overview of {title}", "Key concepts and terminology", "Why the topic matters"]}]
    for i in range(1, max(1,n)):
        slides.append({"title": f"{title}: Part {i}", "bullets":[
            f"Core idea {i} of {title}",
            "Important points and practical examples",
            "Summary and takeaway"
        ]})
    return slides[:n]

def create_ppt(title: str, slides: list[dict] | None = None, output_dir: str | None = None) -> str:
    title = title.strip() or "Student Presentation"
    count = min(max(len(slides or []), 3), 15)
    outline = slides if slides else _fallback_outline(title, count)
    outdir = Path(output_dir or (Path.home()/"Documents"/"AURA Presentations"))
    outdir.mkdir(parents=True, exist_ok=True)
    path = outdir / f"{_safe_name(title)}_{datetime.now():%Y%m%d_%H%M%S}.pptx"

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    for idx, item in enumerate(outline):
        layout = prs.slide_layouts[0 if idx == 0 else 1]
        slide = prs.slides.add_slide(layout)
        slide.shapes.title.text = str(item.get("title") or title)
        if idx == 0:
            subtitle = slide.placeholders[1]
            subtitle.text = "Generated by AURA"
        else:
            tf = slide.placeholders[1].text_frame
            tf.clear()
            bullets = item.get("bullets") or []
            for j, bullet in enumerate(bullets[:8]):
                p = tf.paragraphs[0] if j == 0 else tf.add_paragraph()
                p.text = str(bullet)
                p.font.size = Pt(24)
                p.level = 0
    prs.save(path)
    return str(path)

def parse_outline(text: str, title: str, count: int) -> list[dict]:
    try:
        raw=text.strip()
        if raw.startswith("```"):
            raw=re.sub(r"^```(?:json)?\s*|\s*```$","",raw,flags=re.I|re.S)
        data=json.loads(raw)
        if isinstance(data,dict): data=data.get("slides",[])
        if isinstance(data,list):
            cleaned=[]
            for x in data:
                if isinstance(x,dict) and x.get("title"):
                    bullets=x.get("bullets",[])
                    if isinstance(bullets,list):
                        cleaned.append({"title":str(x["title"]), "bullets":[str(b) for b in bullets[:8]]})
            if cleaned: return cleaned[:count]
    except Exception:
        pass
    return _fallback_outline(title,count)
