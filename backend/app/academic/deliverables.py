# 3. POWERPOINT PRESENTATION GENERATION (Academic Seminars)
# ==============================================================================

def create_academic_presentation(
    title: str,
    slides_data: list[dict[str, Any]] | None = None,
    slide_count: int = 10,
    output_filename: str | None = None,
    subtitle: str | None = None,
    presenter: str | None = None,
    slides: list[dict[str, Any]] | None = None,
) -> str:
    """Creates a PowerPoint presentation (.pptx) tailored for college seminars."""
    out_dir = _get_export_dir("Presentations")
    filename = output_filename or f"{_safe_filename(title)}_{datetime.now():%Y%m%d_%H%M%S}.pptx"
    file_path = out_dir / filename

    prs = Presentation()
    prs.slide_width = PptInches(13.333)
    prs.slide_height = PptInches(7.5)

    data = slides or slides_data
    count = min(max(slide_count, 4), 16)

    sub_text = subtitle or f"College Academic Seminar Presentation\nPresenter: {presenter or 'Student'}\nGenerated by JARVIS AI Companion"

    if not data:
        data = [
            {"title": title, "subtitle": sub_text, "bullets": []},
            {"title": "1. Introduction & Motivation", "bullets": [f"Background overview of {title}", "Why this topic is crucial in modern engineering", "Key challenges addressed in this seminar", "Scope and structure of the presentation"]},
            {"title": "2. Literature Review", "bullets": ["Historical evolution of foundational theories", "State-of-the-art benchmarks in recent publications", "Comparative analysis of traditional versus modern paradigms", "Research gaps identified"]},
            {"title": "3. System Architecture", "bullets": ["High-level block diagram and component interaction", "Data flow and execution pipeline", "Key modules and computational requirements", "Integration with existing platforms"]},
            {"title": "4. Core Methodology", "bullets": ["Mathematical formulation and algorithmic design", "Step-by-step procedural workflow", "Parameter tuning and optimization strategies", "Handling edge cases and fault-tolerance"]},
            {"title": "5. Performance Evaluation", "bullets": ["Experimental setup and test datasets", "Execution time and memory footprint analysis", "Comparative benchmark charts and graphs", "Statistical significance of results"]},
            {"title": "6. Practical Applications", "bullets": ["Industrial case studies and deployment scenarios", "Educational and student research applications", "Future integration with autonomous agents", "Real-world impact"]},
            {"title": "7. Conclusion & Summary", "bullets": [f"Summary of findings regarding {title}", "Key engineering takeaways", "Recommendations for academic projects", "Open floor for Q&A"]},
        ][:count]

    for idx, slide_info in enumerate(data):
        layout = prs.slide_layouts[0 if idx == 0 else 1]
        slide = prs.slides.add_slide(layout)

        slide.shapes.title.text = str(slide_info.get("title", title))
        if idx == 0:
            subtitle = slide.placeholders[1]
            subtitle.text = slide_info.get("subtitle", "Generated by JARVIS Academic Companion")
        else:
            tf = slide.placeholders[1].text_frame
            tf.clear()
            for b in slide_info.get("bullets", []):
                p = tf.add_paragraph()
                p.text = str(b)
                p.level = 0
                p.font.size = PptPt(18)
                p.font.name = "Segoe UI"

    prs.save(str(file_path))
    return str(file_path)


