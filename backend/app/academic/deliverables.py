# 4. STUDY MATERIAL GENERATION (Flashcards, Formula Sheets, Question Banks)
# ==============================================================================

def create_study_pack(
    subject: str,
    topic: str,
    material_type: str = "revision",
    flashcards: list[dict[str, str]] | None = None,
    key_formulas: list[dict[str, str]] | None = None,
    exam_questions: list[dict[str, Any]] | None = None,
    output_filename: str | None = None,
) -> str:
    """Generates revision sheets, flashcards, or question banks."""
    out_dir = _get_export_dir("StudyPacks")
    safe_topic = _safe_filename(topic)
    filename = output_filename or f"{_safe_filename(subject)}_{safe_topic}_{material_type}_{datetime.now():%Y%m%d_%H%M%S}.md"
    file_path = out_dir / filename

    header = f"# JARVIS STUDY PACK: {subject.upper()}\n\n"
    header += f"**Topic**: {topic}  \n"
    header += f"**Category**: {material_type.upper()}  \n"
    header += f"**Generated**: {datetime.now():%Y-%m-%d %H:%M}  \n\n"
    header += "---\n\n"

    sections = []

    # 1. Flashcards section
    if flashcards:
        sections.append("## 🗂️ High-Yield Flashcards\n")
        for i, card in enumerate(flashcards, 1):
            q = card.get("q", card.get("question", ""))
            a = card.get("a", card.get("answer", ""))
            sections.append(f"### Card {i}\n**Q**: {q}\n\n**A**: {a}\n")
    elif "flashcard" in material_type.lower():
        sections.append("## 🗂️ High-Yield Flashcards\n")
        sections.append(
            "### Card 1\n**Q**: What is the core definition of " + topic + "?\n\n"
            "**A**: The foundational concept describing the systematic structure and governing mechanisms in " + subject + ".\n\n"
            "### Card 2\n**Q**: What are the two primary advantages?\n\n"
            "**A**: 1. High computational efficiency.\n2. Minimized redundancy and enhanced modularity.\n\n"
            "### Card 3\n**Q**: What is a critical invariant?\n\n"
            "**A**: Maintaining consistency and transaction integrity under concurrent workloads.\n"
        )

    # 2. Key Formulas / Invariants section
    if key_formulas:
        sections.append("## 📐 Key Formulas & Invariants\n")
        for f in key_formulas:
            name = f.get("name", "Formula")
            expr = f.get("formula", f.get("expression", ""))
            desc = f.get("desc", f.get("description", ""))
            sections.append(f"- **{name}**: `{expr}` — {desc}\n")
    else:
        sections.append("## 📐 Essential Theorems & Rules\n")
        sections.append(f"- **Complexity Bound**: Time: `O(n log n)`, Space: `O(n)`\n- **Principle**: State transitions in {topic} follow strict deterministic verification.\n")

    # 3. Practice Exam Questions section
    if exam_questions:
        sections.append("## 📝 University Examination & Viva Questions\n")
        for i, eq in enumerate(exam_questions, 1):
            q = eq.get("question", "")
            marks = eq.get("marks", 8)
            ans = eq.get("answer", "")
            sections.append(f"### Question {i} ({marks} Marks)\n**{q}**\n\n*Key points to include*:\n{ans}\n")
    else:
        sections.append("## 📝 University Examination Questions\n")
        sections.append(
            f"1. **Explain the fundamental principles of {topic} with an illustrative diagram.** (8 Marks)\n"
            f"2. **Differentiate between traditional architectures and modern {topic} approaches.** (4 Marks)\n"
            f"3. **Analyze edge-case failure modes and state recovery techniques in {subject}.** (6 Marks)\n"
        )

    full_text = header + "\n".join(sections)
    file_path.write_text(full_text, encoding="utf-8")
    return str(file_path)
