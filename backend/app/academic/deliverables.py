# 1. EXCEL SPREADSHEET GENERATION (Attendance, Marks, Study Schedule)
# ==============================================================================

def create_attendance_tracker(
    subjects: list[str] | None = None,
    target_pct: float = 75.0,
    output_filename: str = "Attendance_Tracker.xlsx"
) -> str:
    """Creates a comprehensive student attendance tracker Excel sheet with formulas."""
    out_dir = _get_export_dir("Spreadsheets")
    file_path = out_dir / f"{_safe_filename(output_filename.replace('.xlsx', ''))}_{datetime.now():%Y%m%d_%H%M%S}.xlsx"

    wb = Workbook()
    ws = wb.active
    ws.title = "Attendance Analysis"

    # Styling definitions
    header_fill = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid")
    header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
    title_font = Font(name="Segoe UI", size=15, bold=True, color="0284C7")
    regular_font = Font(name="Segoe UI", size=10)
    alert_font = Font(name="Segoe UI", size=10, bold=True, color="DC2626")
    safe_font = Font(name="Segoe UI", size=10, bold=True, color="16A34A")

    thin_border = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1'),
    )

    # Title
    ws["A1"] = "COLLEGE ACADEMIC ATTENDANCE TRACKER"
    ws["A1"].font = title_font
    ws["A2"] = f"Generated by JARVIS Student Companion • Target: {target_pct}% Required Attendance"
    ws["A2"].font = Font(name="Segoe UI", size=9, italic=True, color="64748B")

    # Table Headers
    headers = [
        "Subject Code / Name",
        "Total Classes",
        "Classes Attended",
        "Classes Missed",
        "Current %",
        "Status",
        f"Classes Needed for {target_pct}%",
    ]
    for col_idx, h in enumerate(headers, 1):
        cell = ws.cell(row=4, column=col_idx, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    default_subs = subjects or [
        "Database Management Systems",
        "Operating Systems",
        "Computer Networks",
        "Design and Analysis of Algorithms",
        "Artificial Intelligence",
        "Web Technology Laboratory",
    ]

    # Sample baseline data for calculation demonstration
    sample_stats = [
        (42, 36),
        (38, 26),
        (40, 34),
        (44, 39),
        (35, 29),
        (24, 22),
    ]

    row_idx = 5
    for i, sub in enumerate(default_subs):
        tot, att = sample_stats[i % len(sample_stats)]
        missed = tot - att
        pct = (att / tot) * 100 if tot > 0 else 0.0

        # Calculations
        # classes needed = max(0, ceil((target_pct * tot - 100 * att) / (100 - target_pct)))
        needed = 0
        if pct < target_pct:
            needed = max(0, int((target_pct * tot - 100 * att) / (100 - target_pct)) + 1)

        ws.cell(row=row_idx, column=1, value=sub).font = regular_font
        ws.cell(row=row_idx, column=2, value=tot).font = regular_font
        ws.cell(row=row_idx, column=3, value=att).font = regular_font
        ws.cell(row=row_idx, column=4, value=missed).font = regular_font

        pct_cell = ws.cell(row=row_idx, column=5, value=f"{pct:.1f}%")
        status_cell = ws.cell(row=row_idx, column=6)
        needed_cell = ws.cell(row=row_idx, column=7, value=needed)

        if pct < target_pct:
            pct_cell.font = alert_font
            status_cell.value = "Shortage Alert"
            status_cell.font = alert_font
            needed_cell.font = alert_font
        else:
            pct_cell.font = safe_font
            status_cell.value = "Eligible"
            status_cell.font = safe_font
            needed_cell.font = regular_font

        for c in range(1, 8):
            ws.cell(row=row_idx, column=c).border = thin_border
            if c > 1:
                ws.cell(row=row_idx, column=c).alignment = Alignment(horizontal="center")

        row_idx += 1

    # Auto-fit columns
    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = col[0].column_letter
        ws.column_dimensions[col_letter].width = max(max_len + 4, 14)

    wb.save(str(file_path))
    return str(file_path)


def create_assignment_tracker(output_filename: str = "Assignment_Tracker.xlsx") -> str:
    """Creates a detailed student assignment and marks tracker spreadsheet."""
    out_dir = _get_export_dir("Spreadsheets")
    file_path = out_dir / f"{_safe_filename(output_filename.replace('.xlsx', ''))}_{datetime.now():%Y%m%d_%H%M%S}.xlsx"

    wb = Workbook()
    ws = wb.active
    ws.title = "Assignments"

    header_fill = PatternFill(start_color="0F172A", end_color="0F172A", fill_type="solid")
    header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")

    ws["A1"] = "SEMESTER ASSIGNMENT & ASSESSMENT TRACKER"
    ws["A1"].font = Font(name="Segoe UI", size=15, bold=True, color="3B82F6")

    headers = ["Subject", "Assignment Title", "Due Date", "Max Marks", "Scored", "Status", "Submission Portal"]
    for col_idx, h in enumerate(headers, 1):
        cell = ws.cell(row=3, column=col_idx, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center")

    sample_assignments = [
        ("DBMS", "Normalization 1NF-BCNF Case Study", "2026-11-05", 20, 18, "Submitted", "NEC LMS"),
        ("OS", "CPU Scheduling Simulator Implementation", "2026-11-08", 25, 0, "Pending", "NEC LMS"),
        ("Networks", "Socket Programming in Python", "2026-11-12", 20, 0, "In Progress", "GitHub / LMS"),
        ("Algorithms", "Dynamic Programming vs Greedy Proofs", "2026-11-16", 15, 0, "Pending", "NEC LMS"),
    ]

    for row_idx, item in enumerate(sample_assignments, 4):
        for col_idx, val in enumerate(item, 1):
            c = ws.cell(row=row_idx, column=col_idx, value=val)
            c.font = Font(name="Segoe UI", size=10)
            if col_idx in (3, 4, 5, 6):
                c.alignment = Alignment(horizontal="center")

    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        ws.column_dimensions[col[0].column_letter].width = max(max_len + 4, 15)

    wb.save(str(file_path))
    return str(file_path)


