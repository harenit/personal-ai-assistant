# 2. WORD DOCUMENT GENERATION (Reports, Lab Records, Project Documentation)
# ==============================================================================

def create_academic_report(
    title: str,
    subject: str = "Computer Science",
    sections: list[dict[str, Any]] | None = None,
    output_filename: str | None = None,
    student_name: str | None = None,
    department: str | None = None,
    college: str | None = None,
) -> str:
    """Creates a formatted academic report / lab record in Word (.docx) format."""
    out_dir = _get_export_dir("Documents")
    filename = output_filename or f"{_safe_filename(title)}_{datetime.now():%Y%m%d_%H%M%S}.docx"
    file_path = out_dir / filename

    doc = Document()

    # Title styling
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(title.upper())
    title_run.font.name = "Segoe UI"
    title_run.font.size = Pt(22)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(14, 116, 144)  # Deep Cyan

    # Student metadata subtitle
    sub_parts = []
    if student_name:
        sub_parts.append(f"Author: {student_name}")
    if department:
        sub_parts.append(department)
    if college:
        sub_parts.append(college)
    meta_line = "  •  ".join(sub_parts) if sub_parts else f"Course: {subject}"

    sub_p = doc.add_paragraph()
    sub_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = sub_p.add_run(f"{meta_line}  •  Authored via JARVIS Academic Companion  •  {datetime.now():%B %d, %Y}")
    sub_run.font.name = "Segoe UI"
    sub_run.font.size = Pt(10)
    sub_run.font.italic = True
    sub_run.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph()

    default_sections = sections or [
        {
            "heading": "1. Objective and Problem Statement",
            "body": f"The primary objective of this study is to investigate core principles and real-world implementations regarding {title}. It provides theoretical foundations and practical validation for academic coursework.",
        },
        {
            "heading": "2. Theoretical Architecture & Principles",
            "body": f"Architectural design in {title} involves decomposed operational layers, robust validation protocols, and data transformation mechanisms. Key parameters govern performance under concurrent workloads.",
            "bullets": [
                "Fundamental Concept: Core mathematical and algorithmic rules governing the system.",
                "Efficiency Metric: Low latency, predictable throughput, and high fault-tolerance.",
                "Practical Applications: Industrial adoption across enterprise systems and academic research.",
            ],
        },
        {
            "heading": "3. Methodology & Implementation",
            "body": "The methodology utilizes systematic verification, unit testing, and modular pipeline design. The implementation demonstrates verifiable results with step-by-step evaluation.",
        },
        {
            "heading": "4. Conclusion and Future Scope",
            "body": f"In conclusion, the proposed methodology for {title} achieves the target accuracy and compliance requirements. Future investigations may extend this work with distributed scaling and automated monitoring.",
        },
    ]

    for sec in default_sections:
        h = doc.add_heading(sec.get("heading", ""), level=1)
        if h.runs:
            h.runs[0].font.name = "Segoe UI"
            h.runs[0].font.size = Pt(14)
            h.runs[0].font.color.rgb = RGBColor(30, 41, 59)

        if sec.get("body"):
            p = doc.add_paragraph(sec["body"])
            p.paragraph_format.line_spacing = 1.15
            p.paragraph_format.space_after = Pt(6)

        for b in sec.get("bullets", []):
            doc.add_paragraph(b, style="List Bullet")

    doc.save(str(file_path))
    return str(file_path)


