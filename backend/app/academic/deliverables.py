"""Student Academic Deliverable Generation Engine for JARVIS.

Generates real downloadable files:
- Excel spreadsheets (.xlsx) using openpyxl: Attendance trackers, assignment sheets, study planners.
- Word documents (.docx) using python-docx: Lab records, project reports, seminar documentation.
- PowerPoint slides (.pptx) using python-pptx: Academic seminars and project reviews.
- Study materials: Flashcards, question banks, formula sheets, revision notes.
"""
from __future__ import annotations

import os
import re
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor
from pptx import Presentation
from pptx.util import Inches as PptInches, Pt as PptPt


def _safe_filename(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", name.strip()).strip("_")
    return cleaned[:70] or "deliverable"


def _get_export_dir(subdir: str) -> Path:
    env_dir = os.environ.get("JARVIS_EXPORTS_DIR")
    if env_dir:
        try:
            p = Path(env_dir) / subdir
            p.mkdir(parents=True, exist_ok=True)
            return p
        except OSError:
            pass

    try:
        p = Path.home() / "Documents" / "JARVIS Exports" / subdir
        p.mkdir(parents=True, exist_ok=True)
        test_file = p / ".write_test"
        test_file.touch(exist_ok=True)
        test_file.unlink(missing_ok=True)
        return p
    except OSError:
        fallback = Path(__file__).resolve().parent.parent.parent / "generated_deliverables" / subdir
        fallback.mkdir(parents=True, exist_ok=True)
        return fallback


